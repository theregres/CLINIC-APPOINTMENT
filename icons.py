# One icon per clinic service (shown on service chips).
SERVICE_ICONS = {
    "General Checkup": "clipboard",
    "Dental": "tooth",
    "Pediatrics": "smile",
    "Cardiology": "heart",
}
SERVICE_CLASSES = {
    "General Checkup": "svc-general",
    "Dental": "svc-dental",
    "Pediatrics": "svc-pediatrics",
    "Cardiology": "svc-cardiology",
}


def icon(name: str, size: int = 18, cls: str = "") -> Markup:
    body = _ICONS.get(name)
    if body is None:
        raise KeyError(f"Unknown icon '{name}'")
    css = ("icon " + str(escape(cls))).strip()
    return Markup(
        f'<svg class="{css}" width="{int(size)}" height="{int(size)}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        f'aria-hidden="true">{body}</svg>'
    )


def service_icon(service: str) -> str:
    return SERVICE_ICONS.get(service, "clipboard")


def service_class(service: str) -> str:
    return SERVICE_CLASSES.get(service, "svc-general")
